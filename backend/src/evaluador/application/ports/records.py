"""Ports for stored records and encrypted documents."""

from __future__ import annotations

from typing import Protocol


class Records[T](Protocol):
    """A collection of one kind of record, always read inside one organisation."""

    def guardar(self, entidad: T, /) -> None: ...
    def por_id(self, tenant_id: str, entidad_id: str, /) -> T | None: ...
    def listar(self, tenant_id: str, /) -> list[T]: ...
    def eliminar(self, tenant_id: str, entidad_id: str, /) -> None: ...


class DocumentStore(Protocol):
    def guardar(self, tenant_id: str, documento_id: str, contenido: bytes, /) -> None: ...
    def leer(self, tenant_id: str, documento_id: str, /) -> bytes: ...
    def eliminar(self, tenant_id: str, documento_id: str, /) -> None: ...
